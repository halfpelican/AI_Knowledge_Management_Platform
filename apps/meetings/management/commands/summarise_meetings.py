"""``python manage.py summarise_meetings`` — FR-16's summary over stored meetings, recorded.

The Objective 04 run's instrument (docs/decisions.md D-125), and the way a meeting ingested before
FR-16 existed gets its first summary. It summarises the meetings it is given through
``request_summary`` and ``run_summary`` (apps/meetings/summaries.py), the one path the ingestion
hook and ``POST /api/meetings/{id}/summary`` also take, and writes a JSON record of what the model
extracted and what the application did with it, so a measurement reads the rows the application
wrote and nothing is re-derived.

**Selection.** ``--missing`` takes every meeting that has no summary run at all and a transcript
long enough to summarise, oldest first. ``--meeting <uuid>`` names one and repeats; each gets a
NEW run, which is a Regenerate. The two are not combined.

**One meeting at a time, inline.** Each run is created with ``start=False`` and carried by this
process, never also by a background thread, so each meeting costs one run's provider calls. A run
that ends Unavailable is recorded with its reason and the command continues: one failure must not
cost the rest of the run its record. A failed run is queued for retry exactly as any other is. A
meeting whose summary is already being generated by the server is not run a second time: it is
recorded as in progress and left to that run.

**The record** (``--out``) carries the database name, the provider and chat model, the commit
(with the tracked files that were uncommitted), when the run started and finished, the token
counts the provider reported for every summarisation attempt made during the run (read from the
attempts log's own lines, so they are the counts the provider billed), and per meeting: its title,
date and attendees, the run's status and reason, the summary's elements, and every action item as
stored: the description, the owner as the transcript named them and the user it resolved to, the
deadline as said and the date it resolved to, and the passages. The database named ``kmp`` is
refused (D-84 decision 1).
"""

import json
import logging
import re
import time
import uuid
from pathlib import Path

from django.conf import settings
from django.core.management.base import BaseCommand, CommandError
from django.db import connection
from django.utils import timezone

from apps.ai.attempt_log import ATTEMPT_LOGGER_NAME
from apps.core.constants import SUMMARY_READY
from apps.meetings.models import Meeting
from apps.meetings.summaries import (
    TranscriptTooShort,
    action_items_of,
    request_summary,
    run_summary,
    transcript_is_long_enough,
)
from scripts.measurement_record import (
    RecordError,
    git_commit_sha,
    git_tracked_changes,
    refuse_protected_database,
)

_USAGE = re.compile(r"completion_tokens=(\d+) prompt_tokens=(\d+)")


class SummarisationUsage(logging.Handler):
    """Adds up the token counts on the attempts log's summarisation lines while a run is made.

    The attempt loop logs each attempt with what the provider reported (apps/ai/attempt_log.py);
    this reads those lines rather than changing the AIService contract to return usage. An attempt
    whose provider reported no counts adds nothing, and is counted in ``unreported``.
    """

    def __init__(self):
        super().__init__(level=logging.INFO)
        self.attempts = 0
        self.unreported = 0
        self.prompt_tokens = 0
        self.completion_tokens = 0

    def emit(self, record):
        message = record.getMessage()
        if not message.startswith("summarisation attempt"):
            return
        self.attempts += 1
        found = _USAGE.search(message)
        if found is None:
            self.unreported += 1
            return
        self.completion_tokens += int(found.group(1))
        self.prompt_tokens += int(found.group(2))


def meeting_entry(meeting: Meeting, summary, seconds: float) -> dict:
    """One meeting's record: the run, the summary's elements, and the action items as stored."""
    entry = {
        "id": str(meeting.pk),
        "title": meeting.title,
        "meeting_date": meeting.meeting_date.isoformat(),
        "attendees": sorted(record.user.name for record in meeting.attendees.select_related("user")),
        "summary_id": str(summary.pk),
        "run_number": summary.run_number,
        "status": summary.status,
        "failure_reason": summary.failure_reason,
        "queued_for_retry": summary.queued_for_retry,
        "seconds": round(seconds, 3),
    }
    if summary.status != SUMMARY_READY:
        return entry
    entry.update(
        {
            "model": summary.model,
            "summary_text": summary.summary_text,
            "narrative": summary.narrative,
            "decisions": summary.decisions,
            "highlights": summary.highlights,
            "input_truncated": summary.input_truncated,
            "passages_sent": summary.passages_sent,
            "passages_total": summary.passages_total,
            "action_items_extracted": summary.action_items_extracted,
            "action_items": [
                {
                    "description": item.description,
                    "owner_name": item.owner_name,
                    "owner": item.owner.name if item.owner is not None else None,
                    "due_text": item.due_text,
                    "due_date": item.due_date.isoformat() if item.due_date else None,
                    "passages": item.passages,
                    "origin": item.origin,
                    "edited": item.edited,
                }
                for item in action_items_of(meeting)
                if item.summary_id == summary.pk
            ],
        }
    )
    return entry


class Command(BaseCommand):
    help = (
        "Summarise stored meetings with the configured AI provider (FR-16) and record the run "
        "(Objective 04, D-125). Pass --missing, or --meeting <uuid> (repeatable)."
    )

    def add_arguments(self, parser):
        parser.add_argument(
            "--missing",
            action="store_true",
            help="every meeting with no summary run and a transcript long enough, oldest first",
        )
        parser.add_argument(
            "--meeting",
            action="append",
            default=[],
            metavar="UUID",
            help="one meeting by id, given a new run; repeat the option for several",
        )
        parser.add_argument(
            "--out",
            type=Path,
            default=None,
            metavar="PATH",
            help="write the run's JSON record here (the directory is created)",
        )

    def handle(self, *args, **options):
        database = connection.settings_dict["NAME"]
        try:
            refuse_protected_database(database)
        except RecordError as exc:
            raise CommandError(str(exc))
        if options["missing"] and options["meeting"]:
            raise CommandError("--missing and --meeting contradict each other; pass one.")
        if not options["missing"] and not options["meeting"]:
            raise CommandError("Pass --missing, or --meeting <uuid> (repeatable).")

        record = {
            "database": database,
            "provider": settings.AI_PROVIDER,
            "commit": None,
            "uncommitted_tracked_files": [],
            "started": timezone.now().isoformat(),
            "finished": None,
            "selection": "missing" if options["missing"] else "meetings",
            "usage": None,
            "meetings": [],
        }
        try:
            record["commit"] = git_commit_sha()
            record["uncommitted_tracked_files"] = git_tracked_changes()
        except RecordError as exc:
            record["commit_error"] = str(exc)
            self.stderr.write(self.style.WARNING(f"Commit not recorded: {exc}"))

        self.stdout.write(f"Summarising against database {database!r}.")
        usage = SummarisationUsage()
        attempts_logger = logging.getLogger(ATTEMPT_LOGGER_NAME)
        attempts_logger.addHandler(usage)
        try:
            for meeting in self._selected(options):
                record["meetings"].append(self._summarise(meeting))
        finally:
            attempts_logger.removeHandler(usage)

        record["finished"] = timezone.now().isoformat()
        record["usage"] = {
            "attempts": usage.attempts,
            "attempts_without_reported_tokens": usage.unreported,
            "prompt_tokens": usage.prompt_tokens,
            "completion_tokens": usage.completion_tokens,
        }
        ready = sum(1 for entry in record["meetings"] if entry.get("status") == SUMMARY_READY)
        failed = len(record["meetings"]) - ready
        summary_line = (
            f"Done: {ready} ready, {failed} not; {usage.attempts} attempt(s), "
            f"{usage.prompt_tokens} prompt and {usage.completion_tokens} completion tokens reported."
        )
        self.stdout.write(self.style.ERROR(summary_line) if failed else self.style.SUCCESS(summary_line))

        out = options["out"]
        if out is not None:
            out = Path(out)
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(json.dumps(record, indent=2), encoding="utf-8")
            self.stdout.write(f"Record written to {out}.")

    def _selected(self, options):
        if options["missing"]:
            for meeting in Meeting.objects.filter(summaries__isnull=True).order_by("created_at", "pk"):
                if transcript_is_long_enough(meeting):
                    yield meeting
            return
        for raw_id in options["meeting"]:
            try:
                meeting_id = uuid.UUID(raw_id)
            except ValueError:
                raise CommandError(f"--meeting {raw_id!r} is not a UUID.")
            meeting = Meeting.objects.filter(pk=meeting_id).first()
            if meeting is None:
                raise CommandError(f"No meeting has the id {raw_id}.")
            yield meeting

    def _summarise(self, meeting: Meeting) -> dict:
        started = time.perf_counter()
        try:
            summary, is_new = request_summary(meeting, start=False)
        except TranscriptTooShort:
            self.stdout.write(f"{meeting.pk}: too short to summarise")
            return {
                "id": str(meeting.pk),
                "title": meeting.title,
                "error": "too_short",
                "seconds": round(time.perf_counter() - started, 3),
            }
        if not is_new:
            # The server is already generating this meeting's summary. Running it here as well
            # would pay for the same summary twice, so it is recorded and left to that run.
            self.stdout.write(f"{meeting.pk}: a summary is already being generated; left to that run")
            return {
                "id": str(meeting.pk),
                "title": meeting.title,
                "error": "in_progress",
                "seconds": round(time.perf_counter() - started, 3),
            }
        result = run_summary(summary.pk)
        if result is None:
            raise CommandError(f"Meeting {meeting.pk} was deleted while its summary was running.")
        seconds = time.perf_counter() - started
        self.stdout.write(
            f"{meeting.pk}: {result.status}"
            + (f" ({result.failure_reason})" if result.failure_reason else "")
            + f" in {seconds:.1f} s"
        )
        return meeting_entry(meeting, result, seconds)

