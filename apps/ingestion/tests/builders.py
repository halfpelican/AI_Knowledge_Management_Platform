"""Real files, built in memory, for the ingestion tests.

Every fixture file is generated by the same library that will parse it, so the
tests exercise a genuine PDF, DOCX and XLSX rather than a handmade approximation of
one. Nothing binary is committed: a checked-in fixture corpus is arriving separately
and these tests must not depend on it.

Not named test_*.py, so pytest collects the tests and not the builders.
"""

import io
import zipfile

import docx
import openpyxl
from django.core.files.uploadedfile import SimpleUploadedFile


def upload(content: bytes, name: str = "upload.bin") -> SimpleUploadedFile:
    """An UploadedFile, the object an FR-08 request actually hands to ingestion.

    The name is deliberately free to lie about the content: the server decides the
    format from the signature (FR-08), so several tests pass a misleading one.
    """
    return SimpleUploadedFile(name, content)


def pdf_bytes(text: str) -> bytes:
    """A minimal but valid one-page PDF whose only content is ``text``.

    pypdf writes PDFs but has no API for placing text on a page, so the five objects
    of a minimal document are assembled here and the cross-reference offsets are
    computed from the bytes as they are laid down. ``text`` must be ASCII without
    parentheses or backslashes, which is all any test needs.
    """
    stream = f"BT /F1 12 Tf 72 720 Td ({text}) Tj ET".encode("ascii")
    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] "
        b"/Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>",
        b"<< /Length " + str(len(stream)).encode() + b" >>\nstream\n" + stream + b"\nendstream",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    ]
    out = bytearray(b"%PDF-1.4\n")
    offsets = []
    for number, body in enumerate(objects, start=1):
        offsets.append(len(out))
        out += f"{number} 0 obj\n".encode("ascii") + body + b"\nendobj\n"
    xref_at = len(out)
    out += f"xref\n0 {len(objects) + 1}\n".encode("ascii")
    out += b"0000000000 65535 f \n"
    for offset in offsets:
        out += f"{offset:010d} 00000 n \n".encode("ascii")
    out += (
        f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\n"
        f"startxref\n{xref_at}\n%%EOF"
    ).encode("ascii")
    return bytes(out)


def docx_bytes(paragraphs=(), table_rows=()) -> bytes:
    """A real DOCX with the given paragraphs and, optionally, one table."""
    document = docx.Document()
    for paragraph in paragraphs:
        document.add_paragraph(paragraph)
    if table_rows:
        table = document.add_table(rows=len(table_rows), cols=len(table_rows[0]))
        for row_index, row in enumerate(table_rows):
            for column_index, value in enumerate(row):
                table.cell(row_index, column_index).text = value
    buffer = io.BytesIO()
    document.save(buffer)
    return buffer.getvalue()


def xlsx_bytes(sheets) -> bytes:
    """A real XLSX. ``sheets`` maps a sheet name to a list of row tuples."""
    workbook = openpyxl.Workbook()
    workbook.remove(workbook.active)
    for title, rows in sheets.items():
        worksheet = workbook.create_sheet(title)
        for row in rows:
            worksheet.append(list(row))
    buffer = io.BytesIO()
    workbook.save(buffer)
    return buffer.getvalue()


def zip_bytes(entries) -> bytes:
    """A plain ZIP archive: the container DOCX and XLSX share, with other contents."""
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w") as archive:
        for name, content in entries.items():
            archive.writestr(name, content)
    return buffer.getvalue()


def words(count: int, prefix: str = "w") -> str:
    """``count`` distinct whitespace-delimited tokens, so a chunk's contents can be
    checked by position rather than by eye."""
    return " ".join(f"{prefix}{number}" for number in range(count))
